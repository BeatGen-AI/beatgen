#!/usr/bin/env python3
"""Write git-ignored env files that point BeatGen at the local Supabase stack.

Reads `supabase status -o json` (run from the repo root, where supabase/config.toml lives)
and writes:

  backend/.env          Supabase URL/keys, local Postgres URL (sslmode=disable)
  frontend/.env.local   VITE_* values for the dev server

Existing files are never overwritten unless --force is given, so a hand-written .env with
real dev keys is safe. With --if-missing, existing files are left alone without an error
(used by `make local-env` on every boot). Values already exported in the process environment (for example
workspace secrets) take precedence at runtime over these files: python-dotenv and Vite
both leave already-set variables alone.

Usage: python3 scripts/local_env.py [--force | --if-missing]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SUPABASE_CLI = ["npx", "--yes", "supabase@3.2.0"]
REQUIRED_STATUS_KEYS = ("API_URL", "DB_URL", "ANON_KEY", "SERVICE_ROLE_KEY", "JWT_SECRET")


def read_supabase_status() -> dict[str, str]:
    result = subprocess.run(
        [*SUPABASE_CLI, "status", "-o", "json"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit(
            "`supabase status` failed. Is the local stack running? Start it with "
            f"`make supabase-start`.\n{result.stderr.strip()}"
        )
    # The CLI may print notices before the JSON object.
    start = result.stdout.find("{")
    if start == -1:
        sys.exit(f"Could not find JSON in `supabase status` output:\n{result.stdout}")
    status = json.loads(result.stdout[start:])
    missing = [key for key in REQUIRED_STATUS_KEYS if not status.get(key)]
    if missing:
        sys.exit(f"`supabase status` output is missing {missing}: {sorted(status)}")
    return status


def backend_env(status: dict[str, str]) -> str:
    return "\n".join(
        [
            "# Generated by scripts/local_env.py for the LOCAL Supabase stack. Do not commit.",
            "APP_ENV=dev",
            f"SUPABASE_URL={status['API_URL']}",
            f"SUPABASE_KEY={status['ANON_KEY']}",
            f"SUPABASE_SECRET_KEY={status['SERVICE_ROLE_KEY']}",
            f"SUPABASE_JWT_SECRET={status['JWT_SECRET']}",
            # The local Postgres has no TLS; see sqlmodel_client.py for sslmode handling.
            f"DATABASE_URL={status['DB_URL']}?sslmode=disable",
            "USE_DISTRIBUTED_REQUESTS=false",
            "",
            "# Not provided by the local stack. Add real values (or export them) to use these",
            "# features; they fail loudly without them. See backend/.env.example.",
            "# ANTHROPIC_API_KEY=",
            "# OPENAI_API_KEY=",
            "# GEMINI_API_KEY=",
            "# OPENROUTER_API_KEY=",
            "# DEV_STRIPE_SECRET_KEY=",
            "",
        ]
    )


def frontend_env(status: dict[str, str]) -> str:
    return "\n".join(
        [
            "# Generated by scripts/local_env.py for the LOCAL Supabase stack. Do not commit.",
            "VITE_APP_ENV=dev",
            # Empty = same-origin /storage/v1 URLs, proxied by the dev server to the local stack,
            # so assets also load through remote previews (see vite.config.ts).
            "VITE_SUPABASE_URL=",
            f"DEV_SUPABASE_PROXY_TARGET={status['API_URL']}",
            "",
        ]
    )


def write(path: Path, content: str, force: bool, if_missing: bool) -> None:
    if path.exists() and if_missing:
        print(f"kept existing {path.relative_to(REPO_ROOT)}")
        return
    if path.exists() and not force:
        sys.exit(f"{path.relative_to(REPO_ROOT)} already exists; re-run with --force to replace it.")
    path.write_text(content)
    print(f"wrote {path.relative_to(REPO_ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--force", action="store_true", help="overwrite existing env files")
    mode.add_argument("--if-missing", action="store_true", help="only write files that do not exist yet")
    args = parser.parse_args()

    targets = [
        (REPO_ROOT / "backend" / ".env", backend_env),
        (REPO_ROOT / "frontend" / ".env.local", frontend_env),
    ]
    if args.if_missing and all(path.exists() for path, _ in targets):
        print("env files already exist; nothing to do")
        return
    status = read_supabase_status()
    for path, render in targets:
        write(path, render(status), args.force, args.if_missing)


if __name__ == "__main__":
    main()
